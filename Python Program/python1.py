# Integer
age = 25
print("Age:", age)
print("Type of age:", type(age))

# Float
height = 5.8
print("\nHeight:", height)
print("Type of height:", type(height))

# String
name = "Geerthana"
print("\nName:", name)
print("Type of name:", type(name))

# Boolean
is_student = True
print("\nIs Student:", is_student)
print("Type of is_student:", type(is_student))

# List
marks = [85, 90, 88, 92]
print("\nMarks:", marks)
print("Type of marks:", type(marks))

# Tuple
coordinates = (10, 20)
print("\nCoordinates:", coordinates)
print("Type of coordinates:", type(coordinates))

# Set
unique_numbers = {1, 2, 3, 4}
print("\nUnique Numbers:", unique_numbers)
print("Type of unique_numbers:", type(unique_numbers))

# Dictionary
student = {
    "name": "Geerthana",
    "age": 25,
    "course": "Data Analytics"
}
print("\nStudent Details:", student)
print("Type of student:", type(student))
